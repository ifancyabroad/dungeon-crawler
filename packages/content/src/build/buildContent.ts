/**
 * Build step: read all JSON files from src/raw/classes and src/raw/monsters,
 * validate with Zod, write generated/index.ts.
 *
 * Run: pnpm run generate (or tsx src/build/buildContent.ts)
 * Optional: --watch to re-run when raw or schemas change.
 */
/// <reference types="node" />

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync, watch } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CharacterClassSchema, type CharacterClassDefinition } from "../schemas/characterClass.js";
import { MonsterSchema, type MonsterDefinition } from "../schemas/monster.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..", "..");
const RAW_CLASSES_DIR = join(ROOT, "src", "raw", "classes");
const RAW_MONSTERS_DIR = join(ROOT, "src", "raw", "monsters");
const OUT_PATH = join(ROOT, "src", "generated", "index.ts");

function getContentVersion(): string {
	try {
		const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf-8"));
		return typeof pkg.version === "string" ? pkg.version : "dev";
	} catch {
		return "dev";
	}
}

function loadAndValidate<T>(
	dir: string,
	schema: {
		safeParse: (
			d: unknown,
		) => { success: true; data: T } | { success: false; error: { format: () => unknown } };
	},
	label: string,
): T[] | null {
	if (!existsSync(dir)) return [];
	const files = readdirSync(dir)
		.filter((f) => f.endsWith(".json"))
		.sort();
	const items: T[] = [];
	for (const file of files) {
		let parsed: unknown;
		try {
			const raw = readFileSync(join(dir, file), "utf-8");
			parsed = JSON.parse(raw);
		} catch (err) {
			console.error(`Parse failed for ${label}/${file}:`, err);
			return null;
		}
		const result = schema.safeParse(parsed);
		if (!result.success) {
			console.error(`Validation failed for ${label}/${file}:`, result.error.format());
			return null;
		}
		items.push(result.data);
	}
	return items;
}

/**
 * Run generation. Returns false on validation/parse error (caller may exit(1) in one-off mode).
 * In watch mode we never exit so the user can fix the file and save again.
 */
function run(): boolean {
	// --- Classes ---
	const classes = loadAndValidate<CharacterClassDefinition>(
		RAW_CLASSES_DIR,
		CharacterClassSchema,
		"classes",
	);
	if (!classes) return false;

	const classIds = [...new Set(classes.map((c) => c.id))];
	if (classIds.length !== classes.length) {
		console.error("Duplicate character class ids found.");
		return false;
	}
	const sortedClasses = [...classes].sort((a, b) => a.id.localeCompare(b.id, "en"));

	// --- Monsters ---
	const monsters = loadAndValidate<MonsterDefinition>(
		RAW_MONSTERS_DIR,
		MonsterSchema,
		"monsters",
	);
	if (!monsters) return false;

	const monsterIds = [...new Set(monsters.map((m) => m.id))];
	if (monsterIds.length !== monsters.length) {
		console.error("Duplicate monster ids found.");
		return false;
	}
	const sortedMonsters = [...monsters].sort((a, b) => a.id.localeCompare(b.id, "en"));

	// --- Generate ---
	const classIdValues = sortedClasses.map((c) => c.id);
	const monsterIdValues = sortedMonsters.map((m) => m.id);
	mkdirSync(dirname(OUT_PATH), { recursive: true });

	const lines: string[] = [
		"/** Generated by buildContent.ts — do not edit by hand. */",
		"",
		'import type { CharacterClassDefinition } from "../schemas/characterClass.js";',
		'import type { MonsterDefinition } from "../schemas/monster.js";',
		"",
		"export const characterClassIds = " + JSON.stringify(classIdValues) + " as const;",
		"export type CharacterClassId = (typeof characterClassIds)[number];",
		"",
		"export const monsterIds = " + JSON.stringify(monsterIdValues) + " as const;",
		"export type MonsterId = (typeof monsterIds)[number];",
		"",
		`export const contentVersion: string = ${JSON.stringify(getContentVersion())};`,
		"",
		"export const classes: readonly CharacterClassDefinition[] = " +
			JSON.stringify(sortedClasses, null, 2) +
			" as readonly CharacterClassDefinition[];",
		"",
		"const _byId: Record<CharacterClassId, CharacterClassDefinition> = {} as Record<CharacterClassId, CharacterClassDefinition>;",
		"for (const c of classes) { _byId[c.id as CharacterClassId] = c; }",
		"export const classesById: Record<CharacterClassId, CharacterClassDefinition> = _byId;",
		"",
		"export const monsters: readonly MonsterDefinition[] = " +
			JSON.stringify(sortedMonsters, null, 2) +
			" as readonly MonsterDefinition[];",
		"",
		"const _monstersById: Record<MonsterId, MonsterDefinition> = {} as Record<MonsterId, MonsterDefinition>;",
		"for (const m of monsters) { _monstersById[m.id as MonsterId] = m; }",
		"export const monstersById: Record<MonsterId, MonsterDefinition> = _monstersById;",
		"",
	];
	writeFileSync(OUT_PATH, lines.join("\n"), "utf-8");
	console.log("Wrote", OUT_PATH);
	return true;
}

const isWatch = process.argv.includes("--watch");
if (isWatch) {
	run();
	watch(RAW_CLASSES_DIR, () => run());
	watch(RAW_MONSTERS_DIR, () => run());
	watch(join(ROOT, "src", "schemas"), () => run());
} else {
	if (!run()) process.exit(1);
}
