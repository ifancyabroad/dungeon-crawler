/**
 * Build step: read all JSON files from src/raw/classes, src/raw/npcs, src/raw/vaults,
 * and src/raw/encounters, validate with Zod, write generated/index.ts.
 *
 * Run: pnpm run generate (or tsx src/build/buildContent.ts)
 * Optional: --watch to re-run when raw or schemas change.
 */
/// <reference types="node" />

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync, watch } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CharacterClassSchema, type CharacterClassDefinition } from "../schemas/characterClass.js";
import { NpcSchema, type NpcDefinition } from "../schemas/npc.js";
import { VaultDefSchema, type VaultDefinition } from "../schemas/vault.js";
import { EncounterDefSchema, type EncounterDefinition } from "../schemas/encounter.js";
import { SkillDefinitionSchema, type SkillDefinition } from "../schemas/skill.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..", "..");
const RAW_CLASSES_DIR = join(ROOT, "src", "raw", "classes");
const RAW_NPCS_DIR = join(ROOT, "src", "raw", "npcs");
const RAW_VAULTS_DIR = join(ROOT, "src", "raw", "vaults");
const RAW_ENCOUNTERS_DIR = join(ROOT, "src", "raw", "encounters");
const RAW_SKILLS_DIR = join(ROOT, "src", "raw", "skills");
const OUT_PATH = join(ROOT, "src", "generated", "index.ts");

function getContentVersion(): string {
	try {
		const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf-8"));
		return typeof pkg.version === "string" ? pkg.version : "dev";
	} catch {
		return "dev";
	}
}

function loadAndValidate<T>(
	dir: string,
	schema: {
		safeParse: (
			d: unknown,
		) => { success: true; data: T } | { success: false; error: { format: () => unknown } };
	},
	label: string,
): T[] | null {
	if (!existsSync(dir)) return [];
	const files = readdirSync(dir)
		.filter((f) => f.endsWith(".json"))
		.sort();
	const items: T[] = [];
	for (const file of files) {
		let parsed: unknown;
		try {
			const raw = readFileSync(join(dir, file), "utf-8");
			parsed = JSON.parse(raw);
		} catch (err) {
			console.error(`Parse failed for ${label}/${file}:`, err);
			return null;
		}
		const result = schema.safeParse(parsed);
		if (!result.success) {
			console.error(`Validation failed for ${label}/${file}:`, result.error.format());
			return null;
		}
		items.push(result.data);
	}
	return items;
}

function run(): boolean {
	const classes = loadAndValidate<CharacterClassDefinition>(
		RAW_CLASSES_DIR,
		CharacterClassSchema,
		"classes",
	);
	if (!classes) return false;

	const classIds = [...new Set(classes.map((c) => c.id))];
	if (classIds.length !== classes.length) {
		console.error("Duplicate character class ids found.");
		return false;
	}
	const sortedClasses = [...classes].sort((a, b) => a.id.localeCompare(b.id, "en"));

	const npcs = loadAndValidate<NpcDefinition>(RAW_NPCS_DIR, NpcSchema, "npcs");
	if (!npcs) return false;

	const npcIds = [...new Set(npcs.map((n) => n.id))];
	if (npcIds.length !== npcs.length) {
		console.error("Duplicate NPC ids found.");
		return false;
	}
	const sortedNpcs = [...npcs].sort((a, b) => a.id.localeCompare(b.id, "en"));

	const vaults = loadAndValidate<VaultDefinition>(RAW_VAULTS_DIR, VaultDefSchema, "vaults");
	if (!vaults) return false;

	const vaultIds = [...new Set(vaults.map((v) => v.id))];
	if (vaultIds.length !== vaults.length) {
		console.error("Duplicate vault ids found.");
		return false;
	}
	const sortedVaults = [...vaults].sort((a, b) => a.id.localeCompare(b.id, "en"));

	const encounters = loadAndValidate<EncounterDefinition>(
		RAW_ENCOUNTERS_DIR,
		EncounterDefSchema,
		"encounters",
	);
	if (!encounters) return false;

	const encounterIds = [...new Set(encounters.map((e) => e.id))];
	if (encounterIds.length !== encounters.length) {
		console.error("Duplicate encounter ids found.");
		return false;
	}
	const sortedEncounters = [...encounters].sort((a, b) => a.id.localeCompare(b.id, "en"));

	const skills = loadAndValidate<SkillDefinition>(
		RAW_SKILLS_DIR,
		SkillDefinitionSchema,
		"skills",
	);
	if (!skills) return false;

	const skillIdValues = [...new Set(skills.map((s) => s.id))];
	if (skillIdValues.length !== skills.length) {
		console.error("Duplicate skill ids found.");
		return false;
	}
	const sortedSkills = [...skills].sort((a, b) => a.id.localeCompare(b.id, "en"));

	const classIdValues = sortedClasses.map((c) => c.id);
	const npcIdValues = sortedNpcs.map((n) => n.id);
	mkdirSync(dirname(OUT_PATH), { recursive: true });

	const lines: string[] = [
		"/** Generated by buildContent.ts — do not edit by hand. */",
		"",
		'import type { CharacterClassDefinition } from "../schemas/characterClass.js";',
		'import type { NpcDefinition } from "../schemas/npc.js";',
		'import type { VaultDefinition } from "../schemas/vault.js";',
		'import type { EncounterDefinition } from "../schemas/encounter.js";',
		'import type { SkillDefinition } from "../schemas/skill.js";',
		"",
		"export const characterClassIds = " + JSON.stringify(classIdValues) + " as const;",
		"export type CharacterClassId = (typeof characterClassIds)[number];",
		"",
		"export const npcIds = " + JSON.stringify(npcIdValues) + " as const;",
		"export type NpcId = (typeof npcIds)[number];",
		"",
		`export const contentVersion: string = ${JSON.stringify(getContentVersion())};`,
		"",
		"export const classes: readonly CharacterClassDefinition[] = " +
			JSON.stringify(sortedClasses, null, 2) +
			" as readonly CharacterClassDefinition[];",
		"",
		"const _byId: Record<CharacterClassId, CharacterClassDefinition> = {} as Record<CharacterClassId, CharacterClassDefinition>;",
		"for (const c of classes) { _byId[c.id as CharacterClassId] = c; }",
		"export const classesById: Record<CharacterClassId, CharacterClassDefinition> = _byId;",
		"",
		"export const npcs: readonly NpcDefinition[] = " +
			JSON.stringify(sortedNpcs, null, 2) +
			" as readonly NpcDefinition[];",
		"",
		"const _npcsById: Record<NpcId, NpcDefinition> = {} as Record<NpcId, NpcDefinition>;",
		"for (const n of npcs) { _npcsById[n.id as NpcId] = n; }",
		"export const npcsById: Record<NpcId, NpcDefinition> = _npcsById;",
		"",
		"export const vaults: readonly VaultDefinition[] = " +
			JSON.stringify(sortedVaults, null, 2) +
			" as readonly VaultDefinition[];",
		"",
		"const _vaultsById: Record<string, VaultDefinition> = {};",
		"for (const v of vaults) { _vaultsById[v.id] = v; }",
		"export const vaultsById: Record<string, VaultDefinition> = _vaultsById;",
		"",
		"export const encounters: readonly EncounterDefinition[] = " +
			JSON.stringify(sortedEncounters, null, 2) +
			" as readonly EncounterDefinition[];",
		"",
		"const _encountersById: Record<string, EncounterDefinition> = {};",
		"for (const e of encounters) { _encountersById[e.id] = e; }",
		"export const encountersById: Record<string, EncounterDefinition> = _encountersById;",
		"",
		"export const skillIds = " + JSON.stringify(skillIdValues) + " as const;",
		"export type SkillId = (typeof skillIds)[number];",
		"",
		"export const skills: readonly SkillDefinition[] = " +
			JSON.stringify(sortedSkills, null, 2) +
			" as readonly SkillDefinition[];",
		"",
		"const _skillsById: Record<string, SkillDefinition> = {};",
		"for (const s of skills) { _skillsById[s.id] = s; }",
		"export const skillsById: Record<string, SkillDefinition> = _skillsById;",
		"",
	];
	writeFileSync(OUT_PATH, lines.join("\n"), "utf-8");
	console.log("Wrote", OUT_PATH);
	return true;
}

const isWatch = process.argv.includes("--watch");
if (isWatch) {
	run();
	// Only watch raw JSON data directories. Schema changes (TypeScript/Zod code)
	// live in @app/shared and require a dev server restart — this is standard
	// practice for code changes in a monorepo, not something the watch loop handles.
	if (existsSync(RAW_CLASSES_DIR)) watch(RAW_CLASSES_DIR, () => run());
	if (existsSync(RAW_NPCS_DIR)) watch(RAW_NPCS_DIR, () => run());
	if (existsSync(RAW_VAULTS_DIR)) watch(RAW_VAULTS_DIR, () => run());
	if (existsSync(RAW_ENCOUNTERS_DIR)) watch(RAW_ENCOUNTERS_DIR, () => run());
	if (existsSync(RAW_SKILLS_DIR)) watch(RAW_SKILLS_DIR, () => run());
} else {
	if (!run()) process.exit(1);
}
